CREATE OR REPLACE FUNCTION public.enqueue_merchant_product_sync(_product_id uuid, _operation text)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO public.merchant_center_sync_queue (product_id, operation, status, attempts, next_attempt_at, locked_until, last_error, updated_at)
  VALUES (_product_id, _operation, 'pending', 0, now(), NULL, NULL, now())
  ON CONFLICT (product_id) DO UPDATE SET
    operation = EXCLUDED.operation,
    status = 'pending',
    attempts = 0,
    next_attempt_at = now(),
    locked_until = NULL,
    last_error = NULL,
    updated_at = now(),
    version = merchant_center_sync_queue.version + 1;
$$;
REVOKE ALL ON FUNCTION public.enqueue_merchant_product_sync(uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.enqueue_merchant_product_sync(uuid, text) TO service_role;

CREATE OR REPLACE FUNCTION public.queue_merchant_product_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM public.enqueue_merchant_product_sync(OLD.id, 'delete');
    RETURN OLD;
  END IF;

  PERFORM public.enqueue_merchant_product_sync(NEW.id, 'upsert');
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS merchant_center_product_inserted ON public.products;
CREATE TRIGGER merchant_center_product_inserted
  AFTER INSERT ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.queue_merchant_product_change();

DROP TRIGGER IF EXISTS merchant_center_product_updated ON public.products;
CREATE TRIGGER merchant_center_product_updated
  AFTER UPDATE OF name, slug, description, price, compare_at_price, image_url, images,
    category_id, vendor_id, brand, sku, stock_quantity, is_active, is_public, is_preorder, specs
  ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.queue_merchant_product_change();

DROP TRIGGER IF EXISTS merchant_center_product_deleted ON public.products;
CREATE TRIGGER merchant_center_product_deleted
  AFTER DELETE ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.queue_merchant_product_change();

CREATE OR REPLACE FUNCTION public.queue_merchant_category_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.name IS DISTINCT FROM OLD.name THEN
    INSERT INTO public.merchant_center_sync_queue (product_id, operation, status, attempts, next_attempt_at, updated_at)
    SELECT p.id, 'upsert', 'pending', 0, now(), now()
    FROM public.products p
    WHERE p.category_id = NEW.id
    ON CONFLICT (product_id) DO UPDATE SET
      operation = 'upsert',
      status = 'pending',
      attempts = 0,
      next_attempt_at = now(),
      locked_until = NULL,
      last_error = NULL,
      updated_at = now(),
      version = merchant_center_sync_queue.version + 1;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS merchant_center_category_changed ON public.categories;
CREATE TRIGGER merchant_center_category_changed
  AFTER UPDATE OF name ON public.categories
  FOR EACH ROW EXECUTE FUNCTION public.queue_merchant_category_change();

