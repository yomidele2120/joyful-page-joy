CREATE TABLE IF NOT EXISTS public.merchant_center_settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  merchant_account_id text,
  data_source_id text,
  feed_label text NOT NULL DEFAULT 'NG',
  content_language text NOT NULL DEFAULT 'en',
  currency_code text NOT NULL DEFAULT 'NGN',
  enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid
);

INSERT INTO public.merchant_center_settings (id)
VALUES (true)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.merchant_center_sync_queue (
  product_id uuid PRIMARY KEY,
  operation text NOT NULL CHECK (operation IN ('upsert', 'delete')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'failed')),
  attempts integer NOT NULL DEFAULT 0,
  version bigint NOT NULL DEFAULT 1,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  locked_until timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS merchant_center_sync_queue_due_idx
  ON public.merchant_center_sync_queue (next_attempt_at, created_at)
  WHERE status <> 'failed';

CREATE TABLE IF NOT EXISTS public.merchant_center_product_status (
  product_id uuid PRIMARY KEY,
  offer_id text NOT NULL,
  product_title text NOT NULL,
  sync_status text NOT NULL DEFAULT 'pending'
    CHECK (sync_status IN ('pending', 'submitted', 'failed', 'deleted', 'ineligible')),
  approval_status text NOT NULL DEFAULT 'pending'
    CHECK (approval_status IN ('pending', 'approved', 'disapproved', 'not_submitted')),
  issues jsonb NOT NULL DEFAULT '[]'::jsonb,
  last_error text,
  status_error text,
  last_synced_at timestamptz,
  status_checked_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS merchant_center_product_status_recent_idx
  ON public.merchant_center_product_status (updated_at DESC);
CREATE INDEX IF NOT EXISTS merchant_center_product_status_poll_idx
  ON public.merchant_center_product_status (status_checked_at NULLS FIRST)
  WHERE sync_status = 'submitted';

CREATE TABLE IF NOT EXISTS public.merchant_center_sync_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id uuid NOT NULL,
  product_title text NOT NULL,
  operation text NOT NULL,
  result text NOT NULL CHECK (result IN ('submitted', 'deleted', 'ineligible', 'failed')),
  message text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS merchant_center_sync_history_recent_idx
  ON public.merchant_center_sync_history (created_at DESC);

